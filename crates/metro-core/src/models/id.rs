//! Typed ID wrappers for compile-time safety.
//!
//! Each ID type is a newtype wrapper around `u64` (design decision D9), so a
//! [`FolderId`] can never be passed where a [`FeedId`] is expected. Every type
//! has its own textual prefix:
//!
//! | Type            | Prefix | Example |
//! |-----------------|--------|---------|
//! | [`FolderId`]    | `fo`   | `fo3`   |
//! | [`FeedId`]      | `f`    | `f12`   |
//! | [`EntryId`]     | `e`    | `e4031` |
//! | [`SavedItemId`] | `s`    | `s3`    |
//!
//! The prefixed form is the **only** external representation of an ID:
//!
//! - `Display` writes `<prefix><number>`.
//! - `FromStr` parses exactly that form (surrounding whitespace is ignored).
//! - `serde` serializes the same prefixed **string** (`"f12"`, never `12`)
//!   and deserializes only that string form, so an `id` copied from
//!   `--json` output can be passed back to a command verbatim.
//!
//! Storage is unaffected: the database keeps plain integer row ids, and
//! callers convert with [`FeedId::new`] / [`FeedId::inner`] (and the
//! equivalents on the other types).
//!
//! # Parsing rules
//!
//! The leading run of ASCII letters is the prefix and must equal the
//! expected prefix **exactly** (case-sensitive). Because of that, `fo3` is a
//! folder ID and never a feed ID with a typo, and `f3` is never a folder ID.
//! The remainder must be a non-empty run of ASCII digits that fits in `u64`
//! (no sign, no separators). Failures map to [`IdParseError`]:
//!
//! | Input (parsed as [`FeedId`]) | Error                          |
//! |------------------------------|--------------------------------|
//! | `12`                         | [`IdParseError::MissingPrefix`] |
//! | `fo3`, `e12`                 | [`IdParseError::WrongPrefix`]   |
//! | `f`, `fx`, `f+1`, `f1.5`     | [`IdParseError::InvalidNumber`] |
//!
//! Every message names the expected `<prefix><number>` form, which the CLI
//! shows as the hint of its usage error (exit 2).
//!
//! # Implementation
//!
//! All four types are generated by one `typed_id!` macro and share
//! [`parse_prefixed`] plus a generic serde visitor, so the format rules are
//! defined once.

use std::fmt;
use std::marker::PhantomData;
use std::str::FromStr;

use serde::de::{self, Visitor};
use serde::{Deserialize, Deserializer, Serialize, Serializer};

/// Define a typed ID newtype with its prefix-based `Display`, `FromStr`,
/// `Serialize` and `Deserialize` implementations.
///
/// `$prefix` is the exact textual prefix and `$what` a human noun used in
/// the serde "expecting" message (e.g. `a feed ID string like "f<number>"`).
macro_rules! typed_id {
    ($(#[$meta:meta])* $name:ident, $prefix:literal, $what:literal) => {
        $(#[$meta])*
        #[doc = concat!("Displays, parses and serializes as `", $prefix, "<N>`.")]
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
        pub struct $name(pub u64);

        impl $name {
            /// The exact textual prefix of this ID type.
            pub const PREFIX: &'static str = $prefix;

            #[doc = concat!("Create a new `", stringify!($name), "` from a raw numeric ID.")]
            #[must_use]
            pub fn new(id: u64) -> Self {
                Self(id)
            }

            /// Get the raw numeric ID (as stored in the database).
            #[must_use]
            pub fn inner(&self) -> u64 {
                self.0
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                write!(f, "{}{}", Self::PREFIX, self.0)
            }
        }

        impl FromStr for $name {
            type Err = IdParseError;

            fn from_str(s: &str) -> Result<Self, Self::Err> {
                parse_prefixed(s, Self::PREFIX).map(Self)
            }
        }

        impl Serialize for $name {
            fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
                serializer.collect_str(self)
            }
        }

        impl<'de> Deserialize<'de> for $name {
            fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
                deserializer.deserialize_str(PrefixedIdVisitor::<Self>::new(concat!(
                    "a ", $what, " ID string like \"", $prefix, "<number>\""
                )))
            }
        }
    };
}

typed_id!(
    /// Folder ID wrapper (feed folders and saved-item folders alike).
    FolderId,
    "fo",
    "folder"
);

typed_id!(
    /// Feed ID wrapper.
    FeedId,
    "f",
    "feed"
);

typed_id!(
    /// Entry ID wrapper.
    EntryId,
    "e",
    "entry"
);

typed_id!(
    /// Saved item ID wrapper.
    SavedItemId,
    "s",
    "saved item"
);

/// Parse `<prefix><digits>` (after trimming whitespace) into the raw number.
///
/// See the module docs for the exact rules and error mapping.
///
/// # Errors
///
/// Returns [`IdParseError::MissingPrefix`] when the input has no leading
/// letters, [`IdParseError::WrongPrefix`] when it is a well-formed ID with
/// another prefix, and [`IdParseError::InvalidNumber`] otherwise.
fn parse_prefixed(input: &str, prefix: &'static str) -> Result<u64, IdParseError> {
    let s = input.trim();
    let split = s
        .find(|c: char| !c.is_ascii_alphabetic())
        .unwrap_or(s.len());
    let (letters, digits) = s.split_at(split);
    let is_number = !digits.is_empty() && digits.bytes().all(|b| b.is_ascii_digit());

    if letters == prefix {
        if is_number {
            // Only overflow can fail here: `digits` is all ASCII digits.
            return digits
                .parse::<u64>()
                .map_err(|_| IdParseError::InvalidNumber(s.to_string(), prefix));
        }
        return Err(IdParseError::InvalidNumber(s.to_string(), prefix));
    }
    if letters.is_empty() {
        return Err(IdParseError::MissingPrefix(s.to_string(), prefix));
    }
    if is_number {
        return Err(IdParseError::WrongPrefix(s.to_string(), prefix));
    }
    if s.starts_with(prefix) {
        // e.g. `eabc` for an entry: right start, garbage instead of a number.
        Err(IdParseError::InvalidNumber(s.to_string(), prefix))
    } else {
        Err(IdParseError::MissingPrefix(s.to_string(), prefix))
    }
}

/// Serde visitor shared by every typed ID: accepts only the prefixed string
/// form and delegates to the type's `FromStr`.
struct PrefixedIdVisitor<T> {
    /// Text for serde's "invalid type: …, expected …" message.
    expecting: &'static str,
    marker: PhantomData<T>,
}

impl<T> PrefixedIdVisitor<T> {
    fn new(expecting: &'static str) -> Self {
        Self {
            expecting,
            marker: PhantomData,
        }
    }
}

impl<T> Visitor<'_> for PrefixedIdVisitor<T>
where
    T: FromStr<Err = IdParseError>,
{
    type Value = T;

    fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.expecting)
    }

    fn visit_str<E: de::Error>(self, value: &str) -> Result<T, E> {
        value.parse::<T>().map_err(E::custom)
    }
}

/// Error type for ID parsing failures.
///
/// Each variant carries the offending input and the expected prefix, and its
/// message names the expected `<prefix><number>` form.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum IdParseError {
    /// The string had the correct prefix but no valid `u64` number after it.
    InvalidNumber(String, &'static str),
    /// The string was missing the expected prefix (e.g. a bare number).
    MissingPrefix(String, &'static str),
    /// The string is a well-formed ID with another prefix (e.g. the folder
    /// ID `fo3` where a feed ID `f<number>` is expected).
    WrongPrefix(String, &'static str),
}

impl fmt::Display for IdParseError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            IdParseError::InvalidNumber(s, prefix) => {
                write!(
                    f,
                    "invalid number in ID: {s:?} (expected format: {prefix}<number>)"
                )
            }
            IdParseError::MissingPrefix(s, prefix) => {
                write!(
                    f,
                    "missing '{prefix}' prefix in ID: {s:?} (expected format: {prefix}<number>)"
                )
            }
            IdParseError::WrongPrefix(s, prefix) => {
                write!(
                    f,
                    "wrong prefix in ID: {s:?} (expected format: {prefix}<number>)"
                )
            }
        }
    }
}

impl std::error::Error for IdParseError {}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_folder_id_display() {
        assert_eq!(FolderId(12).to_string(), "fo12");
        assert_eq!(FolderId(0).to_string(), "fo0");
        assert_eq!(FolderId(3).to_string(), "fo3");
    }

    #[test]
    fn test_feed_id_display() {
        assert_eq!(FeedId(12).to_string(), "f12");
        assert_eq!(FeedId(0).to_string(), "f0");
    }

    #[test]
    fn test_entry_id_display() {
        assert_eq!(EntryId(12).to_string(), "e12");
        assert_eq!(EntryId(4031).to_string(), "e4031");
        assert_eq!(EntryId(0).to_string(), "e0");
    }

    #[test]
    fn test_saved_item_id_display() {
        assert_eq!(SavedItemId(88).to_string(), "s88");
        assert_eq!(SavedItemId(0).to_string(), "s0");
    }

    #[test]
    fn test_folder_id_from_str() {
        assert_eq!("fo12".parse::<FolderId>().unwrap(), FolderId(12));
        assert_eq!("fo0".parse::<FolderId>().unwrap(), FolderId(0));
        assert_eq!("fo3".parse::<FolderId>().unwrap(), FolderId(3));
    }

    #[test]
    fn test_feed_id_from_str() {
        assert_eq!("f12".parse::<FeedId>().unwrap(), FeedId(12));
        assert_eq!("f0".parse::<FeedId>().unwrap(), FeedId(0));
    }

    #[test]
    fn test_entry_id_from_str() {
        assert_eq!("e12".parse::<EntryId>().unwrap(), EntryId(12));
        assert_eq!("e4031".parse::<EntryId>().unwrap(), EntryId(4031));
    }

    #[test]
    fn test_saved_item_id_from_str() {
        assert_eq!("s3".parse::<SavedItemId>().unwrap(), SavedItemId(3));
    }

    #[test]
    fn test_feed_prefix_rejected_as_folder() {
        let err = "f3".parse::<FolderId>().unwrap_err();
        assert_eq!(err, IdParseError::WrongPrefix("f3".to_string(), "fo"));
        assert!(err.to_string().contains("fo<number>"), "{err}");
    }

    #[test]
    fn test_folder_prefix_rejected_as_feed() {
        let err = "fo3".parse::<FeedId>().unwrap_err();
        assert_eq!(err, IdParseError::WrongPrefix("fo3".to_string(), "f"));
        assert!(err.to_string().contains("f<number>"), "{err}");
    }

    #[test]
    fn test_other_type_prefix_rejected() {
        assert!(matches!(
            "e12".parse::<FeedId>(),
            Err(IdParseError::WrongPrefix(_, "f"))
        ));
        assert!(matches!(
            "s3".parse::<EntryId>(),
            Err(IdParseError::WrongPrefix(_, "e"))
        ));
        assert!(matches!(
            "F12".parse::<FeedId>(),
            Err(IdParseError::WrongPrefix(_, "f"))
        ));
    }

    #[test]
    fn test_id_from_str_missing_prefix() {
        let result = "123".parse::<EntryId>();
        assert!(result.is_err());
        let err = result.unwrap_err();
        assert!(matches!(err, IdParseError::MissingPrefix(_, "e")));
        // Check the error message contains helpful hint
        let msg = err.to_string();
        assert!(msg.contains("e<number>"), "{msg}");
        assert!(matches!(
            "".parse::<FolderId>(),
            Err(IdParseError::MissingPrefix(_, "fo"))
        ));
    }

    #[test]
    fn test_id_from_str_invalid_number() {
        for input in ["eabc", "e", "e+1", "e1.5", "e-1", "e18446744073709551616"] {
            assert!(
                matches!(
                    input.parse::<EntryId>(),
                    Err(IdParseError::InvalidNumber(_, "e"))
                ),
                "{input}"
            );
        }
        assert!(matches!(
            "fo".parse::<FolderId>(),
            Err(IdParseError::InvalidNumber(_, "fo"))
        ));
    }

    #[test]
    fn test_id_from_str_whitespace() {
        assert_eq!("  fo12  ".parse::<FolderId>().unwrap(), FolderId(12));
        assert_eq!("  e4031  ".parse::<EntryId>().unwrap(), EntryId(4031));
    }

    #[test]
    fn test_id_json_roundtrip() {
        fn roundtrip<T>(id: T, expected: &str)
        where
            T: Serialize + for<'de> Deserialize<'de> + PartialEq + fmt::Debug,
        {
            let json = serde_json::to_string(&id).unwrap();
            assert_eq!(json, expected);
            let parsed: T = serde_json::from_str(&json).unwrap();
            assert_eq!(parsed, id);
        }

        roundtrip(FeedId(12), "\"f12\"");
        roundtrip(FolderId(3), "\"fo3\"");
        roundtrip(EntryId(4031), "\"e4031\"");
        roundtrip(SavedItemId(3), "\"s3\"");
    }

    #[test]
    fn test_id_json_rejects_numbers_and_wrong_prefixes() {
        assert!(serde_json::from_str::<FeedId>("12").is_err());
        assert!(serde_json::from_str::<FolderId>("\"f3\"").is_err());
        let err = serde_json::from_str::<FeedId>("\"fo3\"").unwrap_err();
        assert!(err.to_string().contains("f<number>"), "{err}");
    }

    #[test]
    fn test_id_types_not_interchangeable() {
        // This test verifies compile-time type safety.
        // If this compiles, the types are correctly distinct.
        let folder_id = FolderId(1);
        let feed_id = FeedId(1);
        let entry_id = EntryId(1);

        // These would not compile if we tried to use them interchangeably:
        // let _: FeedId = folder_id;  // Compile error
        // let _: EntryId = feed_id;   // Compile error

        // But we can compare their inner values
        assert_eq!(folder_id.inner(), feed_id.inner());
        assert_eq!(feed_id.inner(), entry_id.inner());
    }
}
